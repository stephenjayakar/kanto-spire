// Writes web/src/anim/front_anim_data.js from the pokeemerald decomp: each species' Emerald front-sprite animation
// (the 2-frame anim_front.png flip from src/data/pokemon_graphics/front_pic_anims.h, sprite anim 1) and its motion
// (sMonFrontAnimIdsTable / sMonAnimationDelayTable in src/pokemon.c, run by web/src/anim/front_anim.js).
// Dev tool: only numbers are committed; the frames themselves are the optional Emerald asset pack's
// gfx/pokemon/emerald/<folder>/{front,anim}.png (tools/extract_emerald.py).
//   node tools/extract_front_anims.mjs [path/to/pokeemerald]
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const decomp = path.resolve(process.argv[2] || path.join(root, 'pokeemerald'));
const read = (p) => fs.readFileSync(path.join(decomp, p), 'utf8');

const pics = read('src/data/pokemon_graphics/front_pic_anims.h');
const pokemon = read('src/pokemon.c');

// sAnim_<Name>_1: the frame sequence ([frame, duration in GBA frames], ...)
const seqs = {};
for (const m of pics.matchAll(/static const union AnimCmd sAnim_(\w+)_1\[\] =\s*\{([\s\S]*?)\};/g)) {
  seqs[m[1]] = [...m[2].matchAll(/ANIMCMD_FRAME\((\d+),\s*(\d+)\)/g)].map(f => [+f[1], +f[2]]);
}
// [SPECIES_X] = sAnims_<Name>
const bySpecies = {};
for (const m of pics.matchAll(/\[SPECIES_(\w+)\]\s*=\s*sAnims_(\w+)/g)) bySpecies[m[1]] = m[2];

const table = (name) => {
  const body = pokemon.match(new RegExp(`static const u8 ${name}\\[[^\\]]*\\] =\\s*\\{([\\s\\S]*?)\\};`))[1];
  return Object.fromEntries([...body.matchAll(/\[SPECIES_(\w+)\s*-\s*1\]\s*=\s*(\w+)/g)].map(m => [m[1], m[2]]));
};
const animIds = table('sMonFrontAnimIdsTable');
const delays = table('sMonAnimationDelayTable');

const skip = /^(NONE|EGG|OLD_UNOWN_\w+)$/;
const out = {};
for (const [sp, name] of Object.entries(bySpecies)) {
  if (skip.test(sp) || !seqs[name]) continue;
  const motion = (animIds[sp] || 'ANIM_NONE').replace(/^ANIM_/, '');
  out[sp] = [seqs[name], motion, +(delays[sp] || 0)];
}

const lines = Object.entries(out).map(([sp, [f, m, d]]) => `  ${sp}: [${JSON.stringify(f)}, '${m}'${d ? `, ${d}` : ''}],`);
const src = `// Generated by tools/extract_front_anims.mjs from the pokeemerald decomp; do not edit.
// SPECIES: [[[frame, GBA frames], ...] (front_pic_anims.h sprite anim 1), motion (sMonFrontAnimIdsTable, minus ANIM_),
//           delay in GBA frames before the motion (sMonAnimationDelayTable; omitted when 0)]
export const FRONT_ANIMS = {
${lines.join('\n')}
};
`;
fs.writeFileSync(path.join(root, 'web/src/anim/front_anim_data.js'), src);
console.log(`wrote web/src/anim/front_anim_data.js: ${lines.length} species, ${new Set(Object.values(out).map(v => v[1])).size} motions`);
